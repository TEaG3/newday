// ponytail: linear strcmp over ~140 rows per call (a few dozen calls a frame); index by pointer if it ever shows
const char *lang_pt(const char *en)
{
	for (unsigned i = 0; i < sizeof(pt) / sizeof(pt[0]); i++)
		if (!strcmp(pt[i][0], en)) return pt[i][1];
	return en;
}
